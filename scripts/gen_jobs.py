#!/usr/bin/env python3
"""Generate one per-index job resource from each index_pipelines/<name>.yml config.

Adding an Elasticsearch index to the framework is: add index_pipelines/<name>.yml (and its
views/<view_name>.sql), then rerun this generator. It writes resources/<name>.job.yml, one per
config, all pointing at the shared notebook src/run_index_pipeline.py.

Usage:
  python scripts/gen_jobs.py            # (re)generate resources/<name>.job.yml files
  python scripts/gen_jobs.py --check    # exit non-zero if any generated file is missing/stale

--check is the drift guard: run it in CI (or before deploy) so a config edit that was not
regenerated fails loudly instead of deploying a stale job set.
"""
from __future__ import annotations

import argparse
import glob
import os
import sys

import yaml

_REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_CONFIG_DIR = os.path.join(_REPO_ROOT, "index_pipelines")
_RESOURCES_DIR = os.path.join(_REPO_ROOT, "resources")

# Required keys in every index config. Allow-list: an unknown key is rejected (a typo'd key would
# otherwise be silently ignored, e.g. `primary_keys:` leaving primary_key unset), and a missing key
# is rejected. Both fail closed.
_REQUIRED_KEYS = ("es_index_name", "source_table", "view_name", "primary_key")

# Generated files carry this stamp so no one hand-edits them (edits belong in the config + template).
_GENERATED_HEADER = (
    "# GENERATED by scripts/gen_jobs.py from index_pipelines/{config}. DO NOT EDIT BY HAND.\n"
    "# To change this job: edit the config or the generator template, then rerun the generator.\n"
)


def _config_name(path: str) -> str:
    return os.path.basename(path)[: -len(".yml")]


def load_config(path: str) -> dict:
    """Load and validate one index config. Raises ValueError on any problem (fail closed)."""
    with open(path) as fh:
        cfg = yaml.safe_load(fh)
    if not isinstance(cfg, dict):
        raise ValueError(f"{os.path.basename(path)}: expected a YAML mapping, got {type(cfg).__name__}")

    keys = set(cfg)
    missing = [k for k in _REQUIRED_KEYS if k not in keys or str(cfg[k]).strip() == ""]
    unknown = sorted(keys - set(_REQUIRED_KEYS))
    if missing:
        raise ValueError(f"{os.path.basename(path)}: missing/empty required key(s): {', '.join(missing)}")
    if unknown:
        raise ValueError(
            f"{os.path.basename(path)}: unknown key(s): {', '.join(unknown)}; "
            f"allowed: {', '.join(_REQUIRED_KEYS)}"
        )
    return cfg


def render_job_yaml(config_filename: str, name: str, cfg: dict) -> str:
    """Render the resources/<name>.job.yml content for one index config.

    Deterministic: same config in => byte-identical out, so --check can compare exactly.
    """
    # A stable, unique job key/name per index. base_parameters echo the config values into the
    # shared notebook's widgets. Serverless notebook task (no cluster block), on-demand,
    # CAN_MANAGE_RUN to `users` -- consistent with the other jobs in this bundle.
    return (
        _GENERATED_HEADER.format(config=config_filename)
        + "resources:\n"
        + "  jobs:\n"
        + f"    index_pipeline_{name}:\n"
        + f'      name: "[${{bundle.target}}] databricks-elasticsearch-pipelines: {cfg["es_index_name"]}"\n'
        + "      description: >-\n"
        + f"        Export pipeline for the {cfg['es_index_name']} Elasticsearch index. Runs the shared\n"
        + "        notebook src/run_index_pipeline.py with this index's config. No cluster block =>\n"
        + "        serverless notebook task.\n"
        + "      tasks:\n"
        + f"        - task_key: index_pipeline_{name}\n"
        + "          notebook_task:\n"
        + "            notebook_path: ../src/run_index_pipeline.py\n"
        + "            base_parameters:\n"
        + f'              es_index_name: "{cfg["es_index_name"]}"\n'
        + f'              source_table: "{cfg["source_table"]}"\n'
        + f'              view_name: "{cfg["view_name"]}"\n'
        + f'              primary_key: "{cfg["primary_key"]}"\n'
        + "      permissions:\n"
        + "        - level: CAN_MANAGE_RUN\n"
        + "          group_name: users\n"
    )


def generated_path(name: str) -> str:
    return os.path.join(_RESOURCES_DIR, f"{name}.job.yml")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated files are up to date")
    args = parser.parse_args(argv)

    config_paths = sorted(glob.glob(os.path.join(_CONFIG_DIR, "*.yml")))
    if not config_paths:
        print(f"no index configs found in {_CONFIG_DIR}", file=sys.stderr)
        return 1

    stale = []
    for path in config_paths:
        name = _config_name(path)
        cfg = load_config(path)
        content = render_job_yaml(os.path.basename(path), name, cfg)
        out_path = generated_path(name)

        if args.check:
            existing = None
            if os.path.exists(out_path):
                with open(out_path) as fh:
                    existing = fh.read()
            if existing != content:
                stale.append(name)
        else:
            with open(out_path, "w") as fh:
                fh.write(content)
            print(f"wrote {os.path.relpath(out_path, _REPO_ROOT)}")

    if args.check:
        if stale:
            print(
                "stale/missing generated job file(s) for: " + ", ".join(stale)
                + "\nrun: python scripts/gen_jobs.py",
                file=sys.stderr,
            )
            return 1
        print(f"all {len(config_paths)} generated job file(s) up to date")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
